"""Write docs/mapping-proposal.md from mapping.json and objects.json: every parameter's object, gesture and
effects, the spare objects shuffle can use, and the notes. Run after editing the mapping:

    python3 -I tools/mapping_report.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "art" / "golden-pyramid-with-tunnel-celebration"
NAMES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]


def main() -> None:
    m = json.loads((ROOT / "mapping.json").read_text())
    objs = json.loads((ART / "objects.json").read_text())["objects"]
    plugin = json.loads((ROOT / "web" / "public" / "tonewheel" / "plugin.json").read_text())
    pname = {p["id"]: p["name"] for p in plugin["parameters"]}
    params = [b for b in m["bindings"] if "param" in b]
    notes = [b for b in m["bindings"] if "note" in b]
    used = {b.get("object") for b in params}

    def fx(b: dict) -> str:
        out = []
        for e in b["effects"]:
            extra = "".join(f" {k} {e[k]}" for k in ("parts", "from", "edge", "turn", "toward", "count", "span", "ease") if k in e)
            out.append(f"{e['effect']} {e.get('amount', 1):g}{extra}")
        return ", ".join(out)

    lines = [
        "# Mapping proposal",
        "",
        "*Generated by `tools/mapping_report.py` from `mapping.json` and `art/<slug>/objects.json`; regenerate after edits.*",
        "",
        f"{len(params)} parameters on {len(used)} objects, {len(notes)} notes on single shapes. Display only = no gesture:",
        "the object shows the value but touching it does nothing (routing, tuning and level).",
        "",
        "| parameter | name | object | gesture | effects | lock |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for b in params:
        o = b.get("object") or f"part {b.get('part')}"
        lines.append(f"| `{b['param']}` | {pname.get(b['param'], '')} | {o} | {b.get('gesture', 'display only')} | {fx(b)} | {'locked' if b.get('locked') else ''} |")
    spare = [k for k in objs if k not in used]
    lines += ["", f"## Objects ({len(objs)})", "", "| object | what it is | fills | bound to |", "| --- | --- | --- | --- |"]
    by_obj = {b.get("object"): b["param"] for b in params}
    for k, o in objs.items():
        fills = " ".join(f for ids in o["parts"].values() for f in ids)
        lines.append(f"| {k} | {o.get('label', '')} | {fills} | {('`' + by_obj[k] + '`') if k in by_obj else 'spare (shuffle only)'} |")
    lines += ["", f"Spare objects: {', '.join(spare) if spare else 'none'}.", "", "## Notes", "",
              "Bigger shapes play lower notes; the shapes are spread over the whole canvas so a chord lights several places.", "",
              "| note | shape | | note | shape | | note | shape | | note | shape |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    cells = [f"{NAMES[b['note'] % 12]}{b['note'] // 12 - 1} ({b['note']}) | {b.get('part') or b.get('object')}" for b in sorted(notes, key=lambda b: b["note"])]
    for i in range(0, len(cells), 4):
        row = cells[i:i + 4] + ["|"] * (4 - len(cells[i:i + 4]))
        lines.append("| " + " | | ".join(row) + " |")
    (ROOT / "docs" / "mapping-proposal.md").write_text("\n".join(lines) + "\n")
    print(f"wrote docs/mapping-proposal.md: {len(params)} parameters, {len(objs)} objects, {len(notes)} notes")


if __name__ == "__main__":
    main()
